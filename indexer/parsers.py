"""Tree-sitter parsing with a documented fallback.

Primary path: tree-sitter grammars (python / javascript / typescript).
If a grammar cannot be loaded in an environment, the extractor falls back
to Python's stdlib `ast` module (Python) and a regex parser (JS/TS).
`PARSER_BACKEND` reports which path is actually in use — never claimed
otherwise. See docs/ARCHITECTURE.md.
"""
from __future__ import annotations
import ast, re
from dataclasses import dataclass, field

SUPPORTED = {"python": [".py"], "javascript": [".js", ".jsx", ".mjs"],
             "typescript": [".ts", ".tsx"]}

def language_for_path(path: str) -> str | None:
    p = path.lower()
    for lang, exts in SUPPORTED.items():
        if any(p.endswith(e) for e in exts):
            return lang
    return None

def is_generated_or_minified(path: str, text: str) -> bool:
    if any(s in path for s in ("/node_modules/", "/.venv/", "/dist/", "/build/",
                               "__pycache__", ".min.js")):
        return True
    lines = text.splitlines()
    if lines and max((len(l) for l in lines), default=0) > 2000 and len(lines) < 20:
        return True  # minified: very long lines, few of them
    if "generated by" in text[:500].lower() or "@generated" in text[:500]:
        return True
    return False

# ---------------------------------------------------------------- tree-sitter
_TS_LANGS = {}
PARSER_BACKEND = "fallback"

def _load_ts():
    global PARSER_BACKEND
    try:
        from tree_sitter import Language, Parser  # noqa
        import tree_sitter_python, tree_sitter_javascript, tree_sitter_typescript
        _TS_LANGS["python"] = Language(tree_sitter_python.language())
        _TS_LANGS["javascript"] = Language(tree_sitter_javascript.language())
        _TS_LANGS["typescript"] = Language(tree_sitter_typescript.language_typescript())
        PARSER_BACKEND = "tree-sitter"
        return True
    except Exception:
        PARSER_BACKEND = "fallback"
        return False

_TS_OK = _load_ts()

def ts_parse(language: str, code: bytes):
    """Return a tree-sitter tree, or None if tree-sitter is unavailable."""
    if not _TS_OK or language not in _TS_LANGS:
        return None
    from tree_sitter import Parser
    return Parser(_TS_LANGS[language]).parse(code)

# ---------------------------------------------------------------- fallback
@dataclass
class SymbolInfo:
    qualified_name: str
    kind: str  # function | method | class
    language: str
    start_line: int
    end_line: int
    signature: str = ""
    docstring: str = ""
    body: str = ""
    calls: list = field(default_factory=list)  # list[(name, line)]
    imports: list = field(default_factory=list)
    decorators: list = field(default_factory=list)
    path: str = ""

def _py_ast_symbols(source: str) -> list[SymbolInfo]:
    """Stdlib ast fallback for Python (used only if tree-sitter missing)."""
    out: list[SymbolInfo] = []
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return out
    lines = source.splitlines()
    def body_of(node):
        return "\n".join(lines[node.lineno - 1: node.end_lineno or node.lineno])
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            calls = [n.func.id for n in ast.walk(node)
                     if isinstance(n, ast.Call) and isinstance(n.func, ast.Name)]
            calls += [n.func.attr for n in ast.walk(node)
                      if isinstance(n, ast.Call) and isinstance(n.func, ast.Attribute)]
            out.append(SymbolInfo(
                qualified_name=node.name, kind="function", language="python",
                start_line=node.lineno, end_line=node.end_lineno or node.lineno,
                signature=" ".join(lines[node.lineno - 1].splitlines()),
                docstring=ast.get_docstring(node) or "", body=body_of(node),
                calls=[(c, node.lineno) for c in calls],
                decorators=[ast.unparse(d) for d in node.decorator_list]))
        elif isinstance(node, ast.ClassDef):
            out.append(SymbolInfo(qualified_name=node.name, kind="class",
                language="python", start_line=node.lineno,
                end_line=node.end_lineno or node.lineno, body=body_of(node),
                docstring=ast.get_docstring(node) or ""))
    return out

_JS_FN = re.compile(r"(?:function\s+([A-Za-z_$][\w$]*)\s*\(|(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*(?:async\s*)?\([^)]*\)\s*=>|([A-Za-z_$][\w$]*)\s*\([^)]*\)\s*\{)")
_JS_CALL = re.compile(r"([A-Za-z_$][\w$]*)\s*\(")

def _js_regex_symbols(source: str, language: str) -> list[SymbolInfo]:
    out: list[SymbolInfo] = []
    lines = source.splitlines()
    for i, line in enumerate(lines, 1):
        m = _JS_FN.search(line)
        if m:
            name = next(g for g in m.groups() if g)
            calls = [(c, i) for c in _JS_CALL.findall(line) if c != name]
            out.append(SymbolInfo(qualified_name=name, kind="function",
                language=language, start_line=i, end_line=i, signature=line.strip(),
                body=line, calls=calls))
    return out
